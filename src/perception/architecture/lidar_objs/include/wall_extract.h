#ifndef _WALL_EXTRACT_H__
#define _WALL_EXTRACT_H__

/* 摘墙：把墙面从聚类输入里分出去，让墙不再充当「物体之间的桥」。

   为什么需要它
   ------------
   本场景是一整圈连续的墙。DBSCAN 用大半径（eps 0.6~0.7）才能保住远处物体的完整，
   而那个半径足以让整圈墙连成一块、并把离墙 0.6 m 以内的真物体一起吸进去
   （objs.json 的 _note_split_off 里已经写明这个代价）。反过来把半径收小又会把
   物体切碎 —— 实测一个 344 点的物体在 0.25 m 下裂成 17 瓣。**墙和物体在几何上
   都是连续曲面，距离判据分不开它们。**

   lidar_cluster.cpp 里已经有半边机制（max(长,宽) > wall_size_m 判 type=5），
   但它**只贴标签、不摘点**，墙的点仍然和物体待在同一个簇里。本模块补上摘点这一步。

   判据（纯几何，不用法向）
   ------------------------
   1. 先在聚类输入上跑一次 DBSCAN(seg_eps, seg_min_pts) 做**预分组** —— 只是连通片
   2. 每片算：点数、z 跨度、XY 最小面积外接矩形的长边 span 与短边 side
   3. 判墙：点数 >= min_points 且 z跨度 > min_zspan
            且 (薄度 side/span < max_thin 或 span > min_span)

   **为什么不用法向**（三种试过的判据都失败了，别再走回去）
   - 全局平面拟合 + 厚度：对**一整圈**墙做平面拟合没有意义。实测最要紧的两片
     （637 点的墙环、270 点）都被判成「不是墙」，只摘掉 28% 的点。
   - 局部法向 + 区域生长：kNN 法向在**极薄的墙**上病态 —— 实测一片 11.64 m 长、
     厚 0.02 m 的平面，中位 |n_z| 却算出 0.309（12 个最近邻沿墙铺开、协方差病态），
     刚好越过阈值。25° 区域生长切出 226 片，按那套阈值只认出 9.5% 的点。
   - |n_z| 当竖直度：合并簇上会退化 —— 四面墙连成的环，PCA 最小方向落在 z 轴，
     报 1.000，一个竖直墙环被报成「水平面」。见 cluster_shape.py 的 verticality()。

   实测效果（4 帧，seg_eps = 0.30*1.10 = 0.33，见 plans/deep-cuddling-grove.md）
   --------------------------------------------------------------------------
   最大簇占**全帧**比例   50.4% / 39.2% / 53.1% / 39.4%  →  7.0% / 9.4% / 12.1% / 9.1%
   最大簇点数             1037 / 556 / 570 / 564        →  143 / 133 / 130 / 131
   非墙簇数               14 / 16 / 12 / 17             →  17 / 18 / 13 / 21
   跨 >3 m 的簇           3 / 4 / 2 / 4                 →  1 / 2 / 1 / 2
   摘掉的点               66% / 63% / 67% / 62%

   注意分母：摘墙后的最大簇「占剩余点」是 20.4% / 25.3% / 37.0% / 23.8%，
   那个数会随着摘掉越多而虚高，**不要**拿它跟摘墙前的比例直接比。
   与摘墙前可比的是占**全帧**那一行。

   seg_eps 必须跟着 cluster_voxel_size 走
   --------------------------------------
   实测 eps 恰好等于体素格距时（体素 0.30 / eps 0.30）面邻接在浮点边界上断掉，
   只摘掉 5.6% 的点。所以绝对值和体素绑死，调用方按
   cluster_voxel_size * wall_seg_eps_ratio 算好 seg_eps 传进来。

   **回放数据上量出的安全带是 [1.06, 1.15]**（四帧扫描 ratio 1.04~1.30 步进
   0.02，见 plans/deep-cuddling-grove.md）：

   - **下限 1.06**：1.04 时实时帧最大非墙簇还有 **260** 点、1.08 时 185 点，
     说明墙还在粘着物体没摘干净；到 1.10 才掉到地板值 143。
   - **上限 ~1.16**：实时帧上那个质心 (6.17, 2.99)、125 点、XY 2.65×1.39、
     z 跨 3.37 m 的真物体，在 1.18 还在、**1.20 被吞**；非墙簇数也在 1.16 之后
     开始掉（实时 17→16→14，离线 27 圈 18→16→15）。
   - 1.10 在四帧上的非墙簇数是 **17 / 18 / 13 / 21**，是每一帧的最高或并列最高。

   **但那份数据每帧逐点相同，看不出帧间不稳。** 2026-09-26 换到真机 R-Fans-32
   （输入点数帧间只波动 1.6%，2193~2229）后实测：ratio 1.10 时**判为墙的点数波动
   22%、最大非墙簇在 143~256 之间跳（74%）** —— 远墙碎片时判墙时留成「物体」
   （250 点、跨 10.17 m 的假目标），残留墙点又桥接物体。原因是墙链路上最紧的一跳
   在 **0.347~0.377 m**：eps 0.330 跨不过去，但**具体断在哪一跳逐帧在变**，于是
   墙片忽大忽小。稳定台地是 ratio ∈ [1.20, 1.30]（墙点波动降到 1.3~7%，
   1.33 以上开始吃物体，1.67 时最大非墙簇从 146 掉到 66），取 **1.27
   （eps 0.381）** 为台地中部。

   1.27 的代价：两面墙被焊成一片 —— 而焊点不是「相邻」
   ---------------------------------------------------
   实测那片 392 点的「墙」= 196 点的弯墙 + 119 点的平墙 + 77 个**地面分割残点**，
   而两片墙真实相距 **1.244 m**（另外两帧 1.855 / 1.507）。那些桥点散在
   9×9 m 的范围里（x −6.35~2.74 / y −17.19~−8.02）、近邻间距中位 0.047 m、
   90 分位 0.18 m，用 eps=0.20 去聚**一个邻居都找不到**。它们是地面分割在掠射角
   下的残点，不是墙。MST 长边切断（墙片 MST 边长中位 0.029、90 分位 0.148、
   最大 0.335 —— **没有可用的阈值**）和抬 seg_min_pts（4 时逐帧在合并/分开之间
   翻，波动仍有 16%；≥5 时墙自己就碎了）都治不了。

   解法：片内局部密度过滤（下面的 density_* 参数）
   -----------------------------------------------
   不动 eps，在每个预分组片内部按「到第 k 近邻的距离 < density_tau」把**实体点**
   挑出来重连，再把没被挑中的点**整帧丢掉**。同一批 15 帧真机上实测：

   | | eps 0.330（ratio 1.10） | eps 0.381（ratio 1.27） | **eps 0.381 + 密度过滤** |
   |---|---|---|---|
   | 最大墙片 span | 11.46 m | **14.03 m（焊住）** | **11.43 m（分开）** |
   | 墙点帧间波动 | 24% | 9% | **4%** |
   | 非墙最大簇 | 160（155~**274**） | 156（143~161） | **123** |

   四个数全面优于前面两档。三条注意：
   1. **必须把稀疏点整帧丢掉**（`density_drop`）。只滤不丢，散点会流回主聚类
      重新当桥，非墙最大簇反而涨到 **207**。
   2. τ 取 **0.15**。0.10 太紧（把墙也切了）、0.20 / 0.25 太松（桥点又连上）。
   3. **代价是每帧丢约 150 个稀疏点（6.8%），远处真正稀疏的真实物体原则上可能
      被误丢。** 本场 15 帧没有发生（墙片内部没有紧凑块），但这是**场景相关**的，
      换场景必须复测 —— 而且密度过滤只解决「墙被焊住」，**不解决**「直角墙算一个
      物体还是两个」。

   直角墙：判据判得出「是不是墙」，判不出「是不是**一面**墙
   -------------------------------------------------------
   用户的抱怨是「现在直角的墙，连带旁边的物品都聚成一团了」。2026-09-27 在真机上
   量清楚了它到底是什么：

   - **不是墙吞了物体。** 对最大墙片逐点做局部薄面检测（半径 0.5 m 邻域 XY 的
     短轴 > 0.34 m 且邻域 z 跨度 > 0.45 m），680 点里命中 **0 个**；墙片内部也没有
     ≥12 点的紧凑块。旁边那些物体（0.41 m 的 111 点、0.56 m 的 36 点、0.62 m 的
     40 点）各自是独立的 `type=2` 目标。
   - **是那个框。** 直角墙以一个 `type=5` 目标发出去，`MinRotateRect` 给的是
     **6.35 × 11.39 × 2.68 m**、中心 (−1.46, 1.70, −0.29) —— 中心落在房间当中，
     框横跨整个转角。站在墙边的物体就落在这个框里（实测 111 点那个有 67/111 个点
     在这个框内），看起来就是「聚成一团」。

   解法是在**已判定为墙的片内部**再拆一层竖平面（`SplitWallFaces`）：3D RANSAC
   只收 `|n_z| <= face_max_tilt` 的平面，取内点里 XY 连通的最大一块，切走，
   剩下的继续找；再把方向相近（<= face_merge_deg）、端点相接（<= face_merge_gap）、
   且合起来仍是薄面的两张面并回去；最后把没归到任何面的点并到最近的那张面上
   （**一个点都不丢**）。

   15 帧真机实测（`/tmp/wall_split2.py` 原型，最大墙片 659~687 点）：

   | | 拆之前 | 拆之后 |
   |---|---|---|
   | 最大墙片的目标数 | 1 | **2（15/15 帧都是 2）** |
   | 面 A | — | 280~304 点，7.6~8.0 m 长，0.19~0.28 m 宽（方向 80~81°） |
   | 面 B | — | 261~281 点，7.6~7.7 m 长，0.88~0.99 m 宽（方向 164°） |
   | 最小外接矩形 | 6.35 × 11.39 m | 约 8.0 × 0.3 m 与 7.7 × 0.9 m，贴着墙 |

   两条为什么这么写：

   - **并面这一步不能省。** 不并的时候 RANSAC 会在同一面墙上多切一刀，面数在
     3 ↔ 4 之间逐帧跳（同一片墙切成 4.6 m + 3.0 m 两段，或合成 7.6 m 一段）。
     并回去之后 15/15 帧稳定 2 面。判据里那条「合起来仍是薄面」是防它把真正相邻的
     两面墙糊成一块方疙瘩。
   - **剩余点并到最近的面、不丢。** 实测剩余 88~136 点、到最近面距离中位 0.30 m、
     最大 1.10 m，局部 3D 短轴 > 0.34 的有 **0 个** —— 它们是墙面的壳（墙面本身略有
     弯曲 / 掠射角的毛边），不是物体。丢掉会让墙看起来变薄、变碎；并进最近的面只是
     让那张面宽一点（面 B 的 0.9 m 宽就是这么来的）。

   拆不出第二张面时返回单个「整片」元素，于是普通直墙（实测 370 点那片 11.6 ×
   0.14 m 的墙）逐位与不拆时相同 —— 这是这个函数唯一的安全性来源。

   **改 cluster_voxel_size 必须重测 ratio 与这两个 density 参数。** */

#include <vector>

#include "dbscan.h"

namespace perception
{

struct WallConfig
{
    bool   enable     = true;
    double seg_eps    = 0.33;   // = cluster_voxel_size * wall_seg_eps_ratio，调用方算好
    int    seg_min_pts = 3;     // 预分组的连通性门槛
    int    min_points = 30;     // 片点数下限。刻意偏严：宁可漏判（少摘）不可误判（多摘）
    double min_zspan  = 1.5;    // 片 z 跨度下限，把水平面（地面残点、桌面）挡在外面
    double max_thin   = 0.15;   // 薄度上限。单面墙约 0.01，环状合并簇约 0.5~0.9
    double min_span   = 3.0;    // XY 跨度上限分支：环状墙的薄度大，靠跨度这一支进来

    /* 片内局部密度过滤，理由与实测数据见文件头「1.27 的代价」那一节。
       density_tau <= 0 或 density_k <= 0 时整条路径不生效，退化成纯几何判据
       （与 1.27 原样逐点相同），A/B 时用得上。 */
    bool   density_drop      = true;  // 稀疏点是否整帧丢弃。false 只影响判墙，点会流回主聚类
    double density_tau       = 0.15;  // 半径：tau 内有 >= k 个其他点才算「实体点」
    int    density_k         = 3;     // 上面那个 k
    int    density_min_piece = 10;    // 片小于这个点数就完全不碰（既不测密度也不丢点）
    int    density_min_pts   = 20;    // 片内实体点少于此就放弃整片（不判墙也不丢点）

    /* 墙片拆成竖平面（SplitWallFaces），理由与实测见文件头「直角墙」那一节。
       face_split=false 时整条路径不生效，一片墙仍旧是一个目标。 */
    bool   face_split      = true;
    int    face_min_pts    = 40;    // 一张面的点数下限；片不足 2*face_min_pts 就不拆
    int    face_iter       = 500;   // RANSAC 抽样次数
    double face_tol        = 0.12;  // 点到面的距离容差
    double face_max_tilt   = 0.35;  // |n_z| 上限：只收近竖直的面（墙是竖的）
    double face_link       = 0.60;  // 面内 XY 连通半径：不相接的两块不能算同一张面
    double face_merge_deg  = 25.0;  // 方向差小于它就考虑并
    double face_merge_gap  = 0.80;  // 端点最近距离小于它才并
    double face_merge_thin = 0.15;  // 并完还得是薄面（宽/长），否则不许并
};

/* XY 平面上的最小面积外接矩形（凸包 + 旋转卡壳）。
   输出最长边 span 与短边 side，与 min_rotate_rect.cpp 的 max(length,width) /
   min(length,width) 同义，所以薄度 = side/span 可以直接和那里的判定对照。

   **不要换成 min_rotate_rect 的 MinRotateRect**：那一版是 O(m²)
   （实测 1037 点 19.8 ms），而这里每帧要对每一片都算一次。

   本函数内层是 O(h²)（h = 凸包点数），不是教科书里的线性旋转卡壳 —— 刻意如此：
   cluster_shape.py:64-95 的 min_area_rect_longest() 就是同一个写法，保持等价才能
   拿两边互相验证（该 Python 版已用生产 MinRotateRect 对过大簇：10.7036 对
   10.70379638671875）。h 只有几十到一两百，O(h²) 是微秒级，不值得为常数优化
   破坏这个可验证性。 */
void MinAreaRectXY(const std::vector<points>& pts,
                   const std::vector<int>&    sel,
                   double&                    span,
                   double&                    side);

/* 摘墙。返回墙片，每个元素是该片各点在 data 里的**原下标**（升序）。
   is_wall[i] 为 1 表示第 i 个点属于某个墙片（用 char 而不是 vector<bool>）。
   is_sparse[i] 为 1 表示第 i 个点是「片内稀疏点」：它所在的预分组片够大
   （>= density_min_piece）、片内实体点也够多（>= density_min_pts），但它自己
   在密度过滤里被剔掉了。调用方应当把这些点**整帧丢掉、不喂主聚类** ——
   留着它们会以 seg_eps 为跳板把隔着 1 m 的两片墙连起来，正是密度过滤要治的病
   （实测不丢时非墙最大簇从 123 涨回 207）。

   没有既 is_wall 又 is_sparse 的点；density_drop=false 或 density 参数配成
   不生效时 is_sparse 全 0。

   内部自建 DBSCAN(seg_eps, seg_min_pts) 做预分组 —— DBSCAN 的构造函数只存两个
   double，自建比让调用方持有更干净，也让本模块能脱离 PointsCluster 单测。 */
std::vector<std::vector<int>> ExtractWalls(const std::vector<points>& data,
                                           const WallConfig&          cfg,
                                           std::vector<char>&         is_wall,
                                           std::vector<char>&         is_sparse);

/* 把一片已经判定为墙的连通片按**竖平面**拆开，每个面单独算一个目标。
   入参 piece 是 data 的原下标；返回每个面的原下标（并起来正好是 piece，一个点不丢）。

   为什么需要：一面 L 形的直角墙在 DBSCAN 眼里是一张连续曲面，天然连成一片。
   判据（点数 / z 跨度 / 薄度）判的是「它是不是墙」，判不出「它是不是**一面**墙」，
   于是整面直角墙以一个目标的形式发出去 —— 最小面积外接矩形 6.26 × 11.42 m，
   那个框横跨整个房间、把旁边站在墙边的物体一起圈在里面。拆成两张面之后，
   每张面的框是 8.0 × 0.23 m 和 7.6 × 0.6 m，贴着墙走。

   只在片内做，**不动判墙判据**：拆出来的每个面仍然是墙，is_wall 不变。
   拆不出第二张面时（普通直墙）返回单个「整片」元素，调用方发出去的东西与
   没有这个函数时逐位相同。 */
std::vector<std::vector<int>> SplitWallFaces(const std::vector<points>& data,
                                             const std::vector<int>&    piece,
                                             const WallConfig&          cfg);

}  // namespace perception

#endif  // _WALL_EXTRACT_H__
